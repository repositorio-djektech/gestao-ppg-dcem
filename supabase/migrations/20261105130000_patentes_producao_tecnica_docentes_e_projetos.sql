-- 3. impactos_vinculos: o docente grava os impactos dos registros a que está vinculado -----------
-- (as políticas *_staff continuam; estas somam, pois políticas permissivas se combinam com OR)
DROP POLICY IF EXISTS "impactos_vinculos_insert_docente" ON public.impactos_vinculos;
CREATE POLICY "impactos_vinculos_insert_docente" ON public.impactos_vinculos
  FOR INSERT TO authenticated
  WITH CHECK (
    public.get_user_role() = 'docente' AND (
      (entidade = 'patentes' AND EXISTS (
        SELECT 1 FROM public.patentes_docentes pd
        WHERE pd.patente_id = impactos_vinculos.entidade_id
          AND pd.docente_id = public.get_user_docente_id()
      ))
      OR
      (entidade = 'producao_tecnica' AND EXISTS (
        SELECT 1 FROM public.producao_tecnica_docentes pd
        WHERE pd.producao_tecnica_id = impactos_vinculos.entidade_id
          AND pd.docente_id = public.get_user_docente_id()
      ))
    )
  );

DROP POLICY IF EXISTS "impactos_vinculos_delete_docente" ON public.impactos_vinculos;
CREATE POLICY "impactos_vinculos_delete_docente" ON public.impactos_vinculos
  FOR DELETE TO authenticated
  USING (
    public.get_user_role() = 'docente' AND (
      (entidade = 'patentes' AND EXISTS (
        SELECT 1 FROM public.patentes_docentes pd
        WHERE pd.patente_id = impactos_vinculos.entidade_id
          AND pd.docente_id = public.get_user_docente_id()
      ))
      OR
      (entidade = 'producao_tecnica' AND EXISTS (
        SELECT 1 FROM public.producao_tecnica_docentes pd
        WHERE pd.producao_tecnica_id = impactos_vinculos.entidade_id
          AND pd.docente_id = public.get_user_docente_id()
      ))
    )
  );

