-- 2. patentes ----------------------------------------------------------------------------------
DROP POLICY IF EXISTS "patentes_insert_staff" ON public.patentes;
DROP POLICY IF EXISTS "patentes_update_staff" ON public.patentes;
DROP POLICY IF EXISTS "patentes_delete_staff" ON public.patentes;

CREATE POLICY "patentes_insert" ON public.patentes
  FOR INSERT TO authenticated
  WITH CHECK (
    public.is_admin_staff() OR (
      public.get_user_role() = 'docente' AND public.get_user_docente_id() IS NOT NULL
    )
  );

CREATE POLICY "patentes_update" ON public.patentes
  FOR UPDATE TO authenticated
  USING (
    public.is_admin_staff() OR (
      public.get_user_role() = 'docente' AND EXISTS (
        SELECT 1 FROM public.patentes_docentes pd
        WHERE pd.patente_id = patentes.id AND pd.docente_id = public.get_user_docente_id()
      )
    )
  )
  WITH CHECK (
    public.is_admin_staff() OR (
      public.get_user_role() = 'docente' AND EXISTS (
        SELECT 1 FROM public.patentes_docentes pd
        WHERE pd.patente_id = patentes.id AND pd.docente_id = public.get_user_docente_id()
      )
    )
  );

CREATE POLICY "patentes_delete" ON public.patentes
  FOR DELETE TO authenticated
  USING (
    public.is_admin_staff() OR (
      public.get_user_role() = 'docente' AND EXISTS (
        SELECT 1 FROM public.patentes_docentes pd
        WHERE pd.patente_id = patentes.id AND pd.docente_id = public.get_user_docente_id()
