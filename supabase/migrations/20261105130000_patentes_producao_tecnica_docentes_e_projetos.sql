-- D-27: o docente vê e faz CRUD só no que é dele em Patentes e Produção Técnica; em Projetos de
-- Pesquisa edita só como coordenador (participante apenas visualiza).
--
-- Hoje patentes e producao_tecnica só têm o nome em texto (`autores`), sem vínculo ao docente, e a
-- RLS só deixa a coordenação escrever. Esta migração cria os vínculos (como `publicacoes_docentes`)
-- e libera o docente apenas sobre os registros a que está vinculado:
--
--   1. patentes_docentes e producao_tecnica_docentes (registro <-> docente), com RLS.
--      O docente só vincula A SI MESMO (igual publicacoes_docentes); a coordenação vincula qualquer um.
--   2. patentes e producao_tecnica: INSERT para docente (o vínculo vem logo depois);
--      UPDATE e DELETE para a coordenação OU para o docente vinculado ao registro.
--   3. impactos_vinculos: o docente grava os impactos só dos registros a que está vinculado
--      (senão criar uma patente falharia na etapa dos impactos sociais).
--   4. projetos_pesquisa_update: coordenação OU o docente coordenador do projeto (antes também
--      aceitava participante).
--
-- Os registros que já existem ficam SEM vínculo: o docente não os vê até a coordenação vincular
-- (a tela sugere docentes pelo nome em `autores`). Nada é preenchido automaticamente.
--
-- Aplicada no projeto PPG-DCEM em 2026-11-04 (supabase db push) e conferida em pg_policies.
-- Reversão: DROP das duas tabelas e
-- recriar as políticas antigas (patentes/producao_tecnica *_staff em
-- 20260421000001_etapa_a1_regras_acesso_fix.sql; impactos_vinculos em 20261025215000).

-- 1. Vínculos ----------------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.patentes_docentes (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patente_id bigint NOT NULL REFERENCES public.patentes(id) ON DELETE CASCADE,
  docente_id bigint NOT NULL REFERENCES public.docentes(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT uq_patentes_docentes UNIQUE (patente_id, docente_id)
);
CREATE INDEX IF NOT EXISTS idx_patentes_docentes_docente ON public.patentes_docentes(docente_id);

CREATE TABLE IF NOT EXISTS public.producao_tecnica_docentes (
  id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  producao_tecnica_id bigint NOT NULL REFERENCES public.producao_tecnica(id) ON DELETE CASCADE,
  docente_id          bigint NOT NULL REFERENCES public.docentes(id) ON DELETE CASCADE,
  created_at          timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT uq_producao_tecnica_docentes UNIQUE (producao_tecnica_id, docente_id)
);
CREATE INDEX IF NOT EXISTS idx_producao_tecnica_docentes_docente
  ON public.producao_tecnica_docentes(docente_id);

ALTER TABLE public.patentes_docentes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.producao_tecnica_docentes ENABLE ROW LEVEL SECURITY;

-- Leitura: qualquer autenticado (a restrição do docente na tela é de interface, P-20).
DROP POLICY IF EXISTS "patentes_docentes_select_all" ON public.patentes_docentes;
