-- 1. Iniciação Científica: permitir nova opção 'iniciacao_extensao' e coluna bolsa_cnpq
DO $$
BEGIN
  -- Remover constraint antiga se existir
  IF EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'iniciacao_cientifica_tipo_check'
  ) THEN
    ALTER TABLE public.iniciacao_cientifica
      DROP CONSTRAINT iniciacao_cientifica_tipo_check;
  END IF;

  -- Adicionar constraint atualizada com 'iniciacao_extensao'
  ALTER TABLE public.iniciacao_cientifica
    ADD CONSTRAINT iniciacao_cientifica_tipo_check
    CHECK (tipo = ANY (ARRAY[
      'iniciacao_cientifica'::text,
      'iniciacao_tecnologica'::text,
      'iniciacao_extensao'::text
    ]));
END $$;

ALTER TABLE public.iniciacao_cientifica
  ADD COLUMN IF NOT EXISTS bolsa_cnpq text NOT NULL DEFAULT '';

-- 2. Discentes: permitir que docentes insiram vínculos apontando para si mesmos
DROP POLICY IF EXISTS "discentes_insert_staff" ON public.discentes;
DROP POLICY IF EXISTS "discentes_insert" ON public.discentes;
CREATE POLICY "discentes_insert" ON public.discentes
  FOR INSERT TO authenticated
  WITH CHECK (
    is_admin_staff() OR (
      (get_user_role() = 'docente'::text) AND
      (docente_orientador_id = get_user_docente_id()) AND
      (get_user_docente_id() IS NOT NULL)
    )
  );

-- 3. Egressos: permitir que docentes insiram vínculos apontando para si mesmos
DROP POLICY IF EXISTS "egressos_insert_staff" ON public.egressos;
DROP POLICY IF EXISTS "egressos_insert" ON public.egressos;
CREATE POLICY "egressos_insert" ON public.egressos
  FOR INSERT TO authenticated
  WITH CHECK (
    is_admin_staff() OR (
      (get_user_role() = 'docente'::text) AND
      (docente_orientador_id = get_user_docente_id()) AND
      (get_user_docente_id() IS NOT NULL)
    )
  );

-- 4. Criar tabela qualis para classificações de publicações
CREATE TABLE IF NOT EXISTS public.qualis (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  estrato text NOT NULL,
  nome text NOT NULL DEFAULT '',
  descricao text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_qualis_estrato ON public.qualis (estrato);

ALTER TABLE public.qualis ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "qualis_select_all" ON public.qualis;
CREATE POLICY "qualis_select_all" ON public.qualis
  FOR SELECT TO authenticated USING (true);

DROP POLICY IF EXISTS "qualis_insert_staff" ON public.qualis;
CREATE POLICY "qualis_insert_staff" ON public.qualis
  FOR INSERT TO authenticated WITH CHECK (is_admin_staff());

DROP POLICY IF EXISTS "qualis_update_staff" ON public.qualis;
CREATE POLICY "qualis_update_staff" ON public.qualis
  FOR UPDATE TO authenticated USING (is_admin_staff()) WITH CHECK (is_admin_staff());

DROP POLICY IF EXISTS "qualis_delete_staff" ON public.qualis;
CREATE POLICY "qualis_delete_staff" ON public.qualis
  FOR DELETE TO authenticated USING (is_admin_staff());

