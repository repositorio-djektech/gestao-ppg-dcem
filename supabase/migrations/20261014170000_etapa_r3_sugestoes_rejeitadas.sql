-- Tabela para persistência de rejeições de sugestões automáticas de vínculos
-- ============================================================================

CREATE TABLE IF NOT EXISTS public.sugestoes_vinculos_rejeitadas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipo_vinculo TEXT NOT NULL, -- 'publicacao_docente' | 'publicacao_coautor' | 'discente_orientador'
  origem_identificador TEXT NOT NULL, -- chave identificadora da entidade de origem (ex: publicacao_id, chave de dedupe ou discente_id)
  alvo_identificador TEXT NOT NULL,   -- chave identificadora do alvo rejeitado (ex: docente_id, discente_id ou nome)
  motivo TEXT,
  rejeitado_por TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_sugestao_vinculo_rejeitada UNIQUE (tipo_vinculo, origem_identificador, alvo_identificador)
);

CREATE INDEX IF NOT EXISTS idx_sugestoes_rejeitadas_tipo_origem 
  ON public.sugestoes_vinculos_rejeitadas(tipo_vinculo, origem_identificador);

-- Habilitar RLS
ALTER TABLE public.sugestoes_vinculos_rejeitadas ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "sugestoes_rejeitadas_select" ON public.sugestoes_vinculos_rejeitadas;
CREATE POLICY "sugestoes_rejeitadas_select" ON public.sugestoes_vinculos_rejeitadas
  FOR SELECT TO authenticated USING (true);

DROP POLICY IF EXISTS "sugestoes_rejeitadas_insert" ON public.sugestoes_vinculos_rejeitadas;
CREATE POLICY "sugestoes_rejeitadas_insert" ON public.sugestoes_vinculos_rejeitadas
  FOR INSERT TO authenticated WITH CHECK (
    public.get_user_role() = ANY (ARRAY['admin'::text, 'editor'::text])
  );

DROP POLICY IF EXISTS "sugestoes_rejeitadas_update" ON public.sugestoes_vinculos_rejeitadas;
CREATE POLICY "sugestoes_rejeitadas_update" ON public.sugestoes_vinculos_rejeitadas
  FOR UPDATE TO authenticated
  USING (public.get_user_role() = ANY (ARRAY['admin'::text, 'editor'::text]))
  WITH CHECK (public.get_user_role() = ANY (ARRAY['admin'::text, 'editor'::text]));

DROP POLICY IF EXISTS "sugestoes_rejeitadas_delete" ON public.sugestoes_vinculos_rejeitadas;
CREATE POLICY "sugestoes_rejeitadas_delete" ON public.sugestoes_vinculos_rejeitadas
  FOR DELETE TO authenticated
  USING (public.get_user_role() = ANY (ARRAY['admin'::text, 'editor'::text]));
