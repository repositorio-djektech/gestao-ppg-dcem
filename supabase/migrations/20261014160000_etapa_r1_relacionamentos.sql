-- ----------------------------------------------------------------------------
-- 3. Coluna classificacao na tabela projetos_pesquisa ('institucional' ou 'individual')
-- ----------------------------------------------------------------------------
ALTER TABLE public.projetos_pesquisa
  ADD COLUMN IF NOT EXISTS classificacao TEXT;

-- Adicionar constraint de checagem idempotente para classificacao
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'projetos_pesquisa_classificacao_check'
  ) THEN
    ALTER TABLE public.projetos_pesquisa
      ADD CONSTRAINT projetos_pesquisa_classificacao_check
      CHECK (classificacao IS NULL OR classificacao = ANY (ARRAY['institucional'::text, 'individual'::text]));
  END IF;
END $$;

-- ----------------------------------------------------------------------------
-- 4. Colunas projeto_id e docente_orientador_id na tabela discentes
-- ----------------------------------------------------------------------------
ALTER TABLE public.discentes
  ADD COLUMN IF NOT EXISTS projeto_id BIGINT REFERENCES public.projetos_pesquisa(id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS docente_orientador_id BIGINT REFERENCES public.docentes(id) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS idx_discentes_projeto_id ON public.discentes(projeto_id);
CREATE INDEX IF NOT EXISTS idx_discentes_docente_orientador_id ON public.discentes(docente_orientador_id);

-- Retroalimentação segura dos FKs de orientador:
-- Apenas correspondência exata (case-insensitive e trim) com docentes existentes.
-- Registros onde orientador é nulo ou vazio não são alterados.
DO $$
DECLARE
  linhas_afetadas INT := 0;
BEGIN
  UPDATE public.discentes d
  SET docente_orientador_id = doc.id
  FROM public.docentes doc
  WHERE d.orientador IS NOT NULL
    AND TRIM(d.orientador) <> ''
    AND LOWER(TRIM(d.orientador)) = LOWER(TRIM(doc.nome))
    AND d.docente_orientador_id IS NULL;

  GET DIAGNOSTICS linhas_afetadas = ROW_COUNT;
  RAISE NOTICE 'Discentes atualizados retroativamente com docente_orientador_id: %', linhas_afetadas;
END $$;

