-- Fundamentação e alinhamento com a Ficha de Avaliação CAPES Engenharias II 2025:
-- 1. linhas_pesquisa e docentes_linhas:
--    Alinhamento ao Item 1.1 da Ficha CAPES (Articulação, aderência e atualização
--    das áreas de concentração, linhas de pesquisa, projetos em andamento e estrutura
--    curricular). Mapeia formalmente quais docentes atuam em quais linhas do programa.
--
-- 2. projetos_pesquisa.classificacao:
--    Permite classificar projetos entre 'institucional' ou 'individual' (opcional,
--    com constraint flexível permitindo NULL para legados), auxiliando a análise de
--    envolvimento do corpo docente e conformidade com critérios de pesquisa CAPES.
--
-- 3. discentes.projeto_id e discentes.docente_orientador_id:
--    Relacionamento formal discente -> projeto de pesquisa e discente -> docente orientador
--    (FKs com ON DELETE SET NULL). Preserva a coluna textual discentes.orientador como
--    fallback histórico e resolve com segurança correspondências exatas.
--    Reflete os Itens 1.2.2 e 2.1 da Ficha CAPES (distribuição de orientação e
--    qualidade/aderência das dissertações e teses).
--
-- 4. publicacoes_docentes:
--    Vínculo N:N publicação <-> docente (ON DELETE CASCADE), permitindo relacionar
--    cada publicação a um ou mais docentes do programa, viabilizando os cálculos
--    centrais da CAPES: DPI (Item 2.4.1), DPD (Item 2.4.2) e ATD (Item 2.1.2).
-- ============================================================================

-- ----------------------------------------------------------------------------
-- 1. Tabela linhas_pesquisa
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.linhas_pesquisa (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome TEXT NOT NULL,
  area TEXT, -- Área de concentração da ficha CAPES (opcional)
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Habilitar RLS em linhas_pesquisa
ALTER TABLE public.linhas_pesquisa ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "linhas_pesquisa_select" ON public.linhas_pesquisa;
CREATE POLICY "linhas_pesquisa_select" ON public.linhas_pesquisa
  FOR SELECT TO authenticated USING (true);

DROP POLICY IF EXISTS "linhas_pesquisa_insert" ON public.linhas_pesquisa;
CREATE POLICY "linhas_pesquisa_insert" ON public.linhas_pesquisa
  FOR INSERT TO authenticated WITH CHECK (
    public.get_user_role() = ANY (ARRAY['admin'::text, 'editor'::text])
  );

DROP POLICY IF EXISTS "linhas_pesquisa_update" ON public.linhas_pesquisa;
CREATE POLICY "linhas_pesquisa_update" ON public.linhas_pesquisa
  FOR UPDATE TO authenticated
  USING (public.get_user_role() = ANY (ARRAY['admin'::text, 'editor'::text]))
  WITH CHECK (public.get_user_role() = ANY (ARRAY['admin'::text, 'editor'::text]));

DROP POLICY IF EXISTS "linhas_pesquisa_delete" ON public.linhas_pesquisa;
CREATE POLICY "linhas_pesquisa_delete" ON public.linhas_pesquisa
  FOR DELETE TO authenticated
  USING (public.get_user_role() = ANY (ARRAY['admin'::text, 'editor'::text]));

-- ----------------------------------------------------------------------------
-- 2. Tabela docentes_linhas (N:N docente <-> linha de pesquisa)
