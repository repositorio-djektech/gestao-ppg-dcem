-- D-32 (H-27): períodos de avaliação CAPES e janela do Lattes configuráveis pela coordenação.
--
-- Antes o quadriênio 2025–2028 estava fixo no código. Agora:
--   * periodos_avaliacao: períodos cadastrados (ex.: 2025–2028, 2029–2031), com UM ativo, que
--     alimenta Indicadores, Recondução e Lacunas. Aceita 3 ou 4 anos (até 10).
--   * ppg_configuracoes: linha única com a janela padrão do import do Lattes (a partir de 2020).
-- Leitura: todo usuário autenticado. Escrita: suporte e coordenador (como ppg_textos, D-17).
-- Semente: "Quadriênio 2025–2028" ativo, janela do Lattes desde 2020.
--
-- Reversão: DROP FUNCTION public.ativar_periodo_avaliacao(bigint);
--           DROP TABLE public.ppg_configuracoes; DROP TABLE public.periodos_avaliacao;

-- 1. Períodos de avaliação ------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.periodos_avaliacao (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome           text    NOT NULL,
  ano_inicio     integer NOT NULL,
  ano_fim        integer NOT NULL,
  ativo          boolean NOT NULL DEFAULT false,
  -- Ano de referência dos indicadores (anos depois dele são "futuros"). Vazio = ano corrente,
  -- limitado ao intervalo do período.
  ano_referencia integer,
  created_at     timestamptz NOT NULL DEFAULT now(),
  updated_at     timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT periodos_avaliacao_anos_validos
    CHECK (ano_inicio >= 1990 AND ano_fim <= 2100 AND ano_inicio <= ano_fim AND ano_fim - ano_inicio <= 9),
  CONSTRAINT periodos_avaliacao_referencia_valida
    CHECK (ano_referencia IS NULL OR (ano_referencia >= 1990 AND ano_referencia <= 2100)),
  CONSTRAINT periodos_avaliacao_nome_preenchido CHECK (btrim(nome) <> '')
);

-- No máximo UM período ativo
CREATE UNIQUE INDEX IF NOT EXISTS periodos_avaliacao_um_ativo
  ON public.periodos_avaliacao ((true)) WHERE ativo;

ALTER TABLE public.periodos_avaliacao ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "periodos_avaliacao_select_all" ON public.periodos_avaliacao;
CREATE POLICY "periodos_avaliacao_select_all"
  ON public.periodos_avaliacao FOR SELECT
  TO authenticated
  USING (true);

DROP POLICY IF EXISTS "periodos_avaliacao_insert_coordenacao" ON public.periodos_avaliacao;
CREATE POLICY "periodos_avaliacao_insert_coordenacao"
  ON public.periodos_avaliacao FOR INSERT
  TO authenticated
  WITH CHECK (public.get_user_role() IN ('suporte', 'coordenador'));

DROP POLICY IF EXISTS "periodos_avaliacao_update_coordenacao" ON public.periodos_avaliacao;
CREATE POLICY "periodos_avaliacao_update_coordenacao"
  ON public.periodos_avaliacao FOR UPDATE
  TO authenticated
  USING (public.get_user_role() IN ('suporte', 'coordenador'))
  WITH CHECK (public.get_user_role() IN ('suporte', 'coordenador'));

-- O período ativo não pode ser apagado (ative outro antes)
DROP POLICY IF EXISTS "periodos_avaliacao_delete_coordenacao" ON public.periodos_avaliacao;
CREATE POLICY "periodos_avaliacao_delete_coordenacao"
  ON public.periodos_avaliacao FOR DELETE
  TO authenticated
  USING (public.get_user_role() IN ('suporte', 'coordenador') AND NOT ativo);

-- Troca o período ativo de forma atômica (o índice único não admite dois ativos nem por um instante)
CREATE OR REPLACE FUNCTION public.ativar_periodo_avaliacao(p_id bigint)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF public.get_user_role() NOT IN ('suporte', 'coordenador') THEN
    RAISE EXCEPTION 'Sem permissão para alterar o período de avaliação.' USING ERRCODE = '42501';
  END IF;
  IF NOT EXISTS (SELECT 1 FROM public.periodos_avaliacao WHERE id = p_id) THEN
    RAISE EXCEPTION 'Período de avaliação inexistente.' USING ERRCODE = 'P0002';
  END IF;
  UPDATE public.periodos_avaliacao SET ativo = false, updated_at = now() WHERE ativo AND id <> p_id;
  UPDATE public.periodos_avaliacao SET ativo = true, updated_at = now() WHERE id = p_id AND NOT ativo;
END;
$$;

REVOKE ALL ON FUNCTION public.ativar_periodo_avaliacao(bigint) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.ativar_periodo_avaliacao(bigint) TO authenticated;

-- 2. Configuração geral (linha única) -------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.ppg_configuracoes (
  id                 integer PRIMARY KEY DEFAULT 1,
  -- Janela padrão do import do Lattes (D-31); fim vazio = até o fim do período ativo ou o ano atual
  lattes_ano_inicio  integer NOT NULL DEFAULT 2020,
  lattes_ano_fim     integer,
  updated_at         timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT ppg_configuracoes_linha_unica CHECK (id = 1),
  CONSTRAINT ppg_configuracoes_janela_valida
    CHECK (lattes_ano_inicio >= 1990 AND lattes_ano_inicio <= 2100
           AND (lattes_ano_fim IS NULL OR (lattes_ano_fim >= lattes_ano_inicio AND lattes_ano_fim <= 2100)))
);

ALTER TABLE public.ppg_configuracoes ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "ppg_configuracoes_select_all" ON public.ppg_configuracoes;
CREATE POLICY "ppg_configuracoes_select_all"
  ON public.ppg_configuracoes FOR SELECT
  TO authenticated
  USING (true);

DROP POLICY IF EXISTS "ppg_configuracoes_insert_coordenacao" ON public.ppg_configuracoes;
CREATE POLICY "ppg_configuracoes_insert_coordenacao"
  ON public.ppg_configuracoes FOR INSERT
  TO authenticated
  WITH CHECK (public.get_user_role() IN ('suporte', 'coordenador'));

DROP POLICY IF EXISTS "ppg_configuracoes_update_coordenacao" ON public.ppg_configuracoes;
CREATE POLICY "ppg_configuracoes_update_coordenacao"
  ON public.ppg_configuracoes FOR UPDATE
  TO authenticated
  USING (public.get_user_role() IN ('suporte', 'coordenador'))
  WITH CHECK (public.get_user_role() IN ('suporte', 'coordenador'));

-- 3. Semente --------------------------------------------------------------------------------
INSERT INTO public.periodos_avaliacao (nome, ano_inicio, ano_fim, ativo)
SELECT 'Quadriênio 2025–2028', 2025, 2028, true
WHERE NOT EXISTS (SELECT 1 FROM public.periodos_avaliacao);

INSERT INTO public.ppg_configuracoes (id, lattes_ano_inicio, lattes_ano_fim)
VALUES (1, 2020, NULL)
ON CONFLICT (id) DO NOTHING;
