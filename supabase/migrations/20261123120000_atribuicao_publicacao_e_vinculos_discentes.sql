-- P-34 / P-35: atribuição de publicação a um só docente, ingresso na UFS e discentes em patentes,
-- produção técnica e eventos.
--
--  1. publicacoes.docente_atribuido_id (IN 02/2026, art. 8º, §7º): quando dois ou mais docentes do
--     programa assinam a mesma publicação, só um pode usá-la no PDQ. O docente (ou a coordenação)
--     indica a quem ela é atribuída; sem indicação vale o orientador do discente coautor.
--  2. docentes.ingresso_ufs (mês/ano, AAAA-MM): tempo de serviço na UFS, último critério de
--     desempate (IN, art. 10, parágrafo único, IV, e art. 11, §1º, IV).
--  3. patentes_discentes, producao_tecnica_discentes e eventos_discentes: discentes ligados à
--     produção ("docentes devem vincular linha de pesquisa, projeto, discentes e produção").
--     Patentes e produção técnica: a coordenação ou o docente vinculado ao registro grava;
--     eventos: só a coordenação (o docente não cria evento). Leitura: qualquer autenticado
--     (a restrição do docente na tela é de interface, P-20).
--
-- Só adiciona; nada é apagado nem reescrito.
-- Reversão: DROP das três tabelas; DROP COLUMN publicacoes.docente_atribuido_id e docentes.ingresso_ufs.

-- 1. Atribuição da publicação ------------------------------------------------------------------
ALTER TABLE public.publicacoes
  ADD COLUMN IF NOT EXISTS docente_atribuido_id bigint REFERENCES public.docentes(id) ON DELETE SET NULL;

-- 2. Ingresso na UFS ----------------------------------------------------------------------------
ALTER TABLE public.docentes
  ADD COLUMN IF NOT EXISTS ingresso_ufs text NOT NULL DEFAULT '';

-- 3. Discentes na produção ----------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.patentes_discentes (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patente_id bigint NOT NULL REFERENCES public.patentes(id) ON DELETE CASCADE,
  discente_id bigint NOT NULL REFERENCES public.discentes(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT uq_patentes_discentes UNIQUE (patente_id, discente_id)
);
CREATE TABLE IF NOT EXISTS public.producao_tecnica_discentes (
  id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  producao_tecnica_id bigint NOT NULL REFERENCES public.producao_tecnica(id) ON DELETE CASCADE,
  discente_id         bigint NOT NULL REFERENCES public.discentes(id) ON DELETE CASCADE,
  created_at          timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT uq_producao_tecnica_discentes UNIQUE (producao_tecnica_id, discente_id)
);
CREATE TABLE IF NOT EXISTS public.eventos_discentes (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  evento_id   bigint NOT NULL REFERENCES public.eventos(id) ON DELETE CASCADE,
  discente_id bigint NOT NULL REFERENCES public.discentes(id) ON DELETE CASCADE,
  created_at  timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT uq_eventos_discentes UNIQUE (evento_id, discente_id)
);
CREATE INDEX IF NOT EXISTS idx_patentes_discentes_discente ON public.patentes_discentes(discente_id);
CREATE INDEX IF NOT EXISTS idx_producao_tecnica_discentes_discente ON public.producao_tecnica_discentes(discente_id);
CREATE INDEX IF NOT EXISTS idx_eventos_discentes_discente ON public.eventos_discentes(discente_id);

ALTER TABLE public.patentes_discentes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.producao_tecnica_discentes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.eventos_discentes ENABLE ROW LEVEL SECURITY;

