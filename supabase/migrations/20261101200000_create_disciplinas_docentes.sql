-- Migration: create disciplinas_docentes junction table
-- Permite vincular N docentes a uma disciplina

CREATE TABLE IF NOT EXISTS public.disciplinas_docentes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  disciplina_id BIGINT NOT NULL REFERENCES public.disciplinas(id) ON DELETE CASCADE,
  docente_id BIGINT NOT NULL REFERENCES public.docentes(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_disciplinas_docentes UNIQUE (disciplina_id, docente_id)
);

CREATE INDEX IF NOT EXISTS idx_disciplinas_docentes_disciplina_id ON public.disciplinas_docentes(disciplina_id);
CREATE INDEX IF NOT EXISTS idx_disciplinas_docentes_docente_id ON public.disciplinas_docentes(docente_id);

-- Migrar docentes_id existentes na tabela disciplinas para a tabela de junção (idempotente)
DO $$
BEGIN
  INSERT INTO public.disciplinas_docentes (disciplina_id, docente_id)
  SELECT d.id, d.docente_id
  FROM public.disciplinas d
  WHERE d.docente_id IS NOT NULL
  ON CONFLICT (disciplina_id, docente_id) DO NOTHING;
END $$;

