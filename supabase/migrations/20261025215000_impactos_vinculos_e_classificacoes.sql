-- Migração: impactos_vinculos, patentes.tipo, eventos.tipo e eventos.nacionalidade
-- Idempotente, não destrutiva, sem alterar/excluir dados existentes
-- ============================================================================

-- 1. TABELA-PONTE impactos_vinculos
CREATE TABLE IF NOT EXISTS public.impactos_vinculos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  impacto_social_id BIGINT NOT NULL REFERENCES public.impacto_social(id) ON DELETE CASCADE,
  entidade TEXT NOT NULL,
  entidade_id BIGINT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT timezone('utc'::text, now())
);

-- Constraint de unicidade para evitar duplicatas do mesmo vínculo
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'uq_impactos_vinculos_impacto_entidade'
  ) THEN
    ALTER TABLE public.impactos_vinculos
      ADD CONSTRAINT uq_impactos_vinculos_impacto_entidade
      UNIQUE (impacto_social_id, entidade, entidade_id);
  END IF;
END $$;

-- Índices para buscas rápidas por impacto e por entidade
CREATE INDEX IF NOT EXISTS idx_impactos_vinculos_impacto_id
  ON public.impactos_vinculos (impacto_social_id);

CREATE INDEX IF NOT EXISTS idx_impactos_vinculos_entidade_registro
  ON public.impactos_vinculos (entidade, entidade_id);

-- RLS para impactos_vinculos
ALTER TABLE public.impactos_vinculos ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "impactos_vinculos_select_all" ON public.impactos_vinculos;
CREATE POLICY "impactos_vinculos_select_all"
  ON public.impactos_vinculos
  FOR SELECT
  TO authenticated
  USING (true);

DROP POLICY IF EXISTS "impactos_vinculos_insert_staff" ON public.impactos_vinculos;
CREATE POLICY "impactos_vinculos_insert_staff"
  ON public.impactos_vinculos
  FOR INSERT
  TO authenticated
  WITH CHECK (public.is_admin_staff());

DROP POLICY IF EXISTS "impactos_vinculos_update_staff" ON public.impactos_vinculos;
CREATE POLICY "impactos_vinculos_update_staff"
  ON public.impactos_vinculos
  FOR UPDATE
  TO authenticated
  USING (public.is_admin_staff())
  WITH CHECK (public.is_admin_staff());

DROP POLICY IF EXISTS "impactos_vinculos_delete_staff" ON public.impactos_vinculos;
CREATE POLICY "impactos_vinculos_delete_staff"
  ON public.impactos_vinculos
  FOR DELETE
  TO authenticated
  USING (public.is_admin_staff());

-- 2. PATENTES — COLUNA tipo (INPI)
ALTER TABLE public.patentes
  ADD COLUMN IF NOT EXISTS tipo TEXT;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'patentes_tipo_check'
  ) THEN
    ALTER TABLE public.patentes
      ADD CONSTRAINT patentes_tipo_check
      CHECK (
        tipo IS NULL OR tipo = ANY (ARRAY[
          'Patente de Invenção (PI)'::text,
          'Modelo de Utilidade (MU)'::text,
          'Certificado de Adição'::text,
          'Desenho Industrial'::text,
          'Programa de Computador'::text,
          'Topografia de Circuitos'::text,
          'Marca'::text
        ])
      );
  END IF;
END $$;

-- 3. EVENTOS — COLUNAS tipo e nacionalidade
ALTER TABLE public.eventos
  ADD COLUMN IF NOT EXISTS tipo TEXT;

ALTER TABLE public.eventos
  ADD COLUMN IF NOT EXISTS nacionalidade TEXT;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'eventos_tipo_check'
  ) THEN
    ALTER TABLE public.eventos
      ADD CONSTRAINT eventos_tipo_check
      CHECK (
        tipo IS NULL OR tipo = ANY (ARRAY[
          'Trabalho'::text,
          'Resumo'::text
        ])
      );
  END IF;
END $$;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'eventos_nacionalidade_check'
  ) THEN
    ALTER TABLE public.eventos
      ADD CONSTRAINT eventos_nacionalidade_check
      CHECK (
        nacionalidade IS NULL OR nacionalidade = ANY (ARRAY[
          'Nacional'::text,
          'Internacional'::text
        ])
      );
  END IF;
END $$;
