-- Migração aditiva para Etapas Q2 e Q3 da Ficha CAPES
-- Preserva 100% dos dados existentes (docentes, discentes, egressos, publicações, etc.)

-- 1. ETAPA Q2: Novos campos para controle de prazo de Jovem Doutor Pesquisador (JDP)
ALTER TABLE public.docentes
  ADD COLUMN IF NOT EXISTS jdp_desde integer,
  ADD COLUMN IF NOT EXISTS ano_doutorado integer;

-- 2. ETAPA Q3: Nível da disciplina ('graduacao' | 'pos_graduacao')
ALTER TABLE public.disciplinas
  ADD COLUMN IF NOT EXISTS nivel text;

-- Restrição de valores permitidos para nivel (graduacao / pos_graduacao)
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'disciplinas_nivel_check'
  ) THEN
    ALTER TABLE public.disciplinas
      ADD CONSTRAINT disciplinas_nivel_check
      CHECK (nivel IS NULL OR nivel = ANY (ARRAY['graduacao'::text, 'pos_graduacao'::text]));
  END IF;
END $$;

-- 3. ETAPA Q3: Nova tabela public.iniciacao_cientifica
-- Registros de Iniciação Científica (IC) e Iniciação Tecnológica (IT)
CREATE TABLE IF NOT EXISTS public.iniciacao_cientifica (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  discente_id bigint REFERENCES public.discentes(id) ON DELETE SET NULL,
  discente_nome text,
  tipo text NOT NULL,
  ano integer,
  docente_orientador_id bigint REFERENCES public.docentes(id) ON DELETE SET NULL,
  projeto_id bigint REFERENCES public.projetos_pesquisa(id) ON DELETE SET NULL,
  titulo text NOT NULL DEFAULT '',
  observacoes text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT iniciacao_cientifica_tipo_check CHECK (tipo = ANY (ARRAY['iniciacao_cientifica'::text, 'iniciacao_tecnologica'::text]))
);

-- Índices de performance para iniciacao_cientifica
CREATE INDEX IF NOT EXISTS idx_ic_docente_orientador_id ON public.iniciacao_cientifica(docente_orientador_id);
CREATE INDEX IF NOT EXISTS idx_ic_discente_id ON public.iniciacao_cientifica(discente_id);
CREATE INDEX IF NOT EXISTS idx_ic_projeto_id ON public.iniciacao_cientifica(projeto_id);
CREATE INDEX IF NOT EXISTS idx_ic_ano ON public.iniciacao_cientifica(ano);
CREATE INDEX IF NOT EXISTS idx_ic_tipo ON public.iniciacao_cientifica(tipo);

-- Habilitar RLS em public.iniciacao_cientifica
ALTER TABLE public.iniciacao_cientifica ENABLE ROW LEVEL SECURITY;

-- Políticas de RLS padronizadas com o projeto (leitura authenticated/anon conforme padrão e escrita admin/editor)
DROP POLICY IF EXISTS "iniciacao_cientifica_select" ON public.iniciacao_cientifica;
CREATE POLICY "iniciacao_cientifica_select" ON public.iniciacao_cientifica
  FOR SELECT TO authenticated
  USING (true);

DROP POLICY IF EXISTS "iniciacao_cientifica_insert" ON public.iniciacao_cientifica;
CREATE POLICY "iniciacao_cientifica_insert" ON public.iniciacao_cientifica
  FOR INSERT TO authenticated
  WITH CHECK (get_user_role() = ANY (ARRAY['admin'::text, 'editor'::text]));

DROP POLICY IF EXISTS "iniciacao_cientifica_update" ON public.iniciacao_cientifica;
CREATE POLICY "iniciacao_cientifica_update" ON public.iniciacao_cientifica
  FOR UPDATE TO authenticated
  USING (get_user_role() = ANY (ARRAY['admin'::text, 'editor'::text]))
  WITH CHECK (get_user_role() = ANY (ARRAY['admin'::text, 'editor'::text]));

DROP POLICY IF EXISTS "iniciacao_cientifica_delete" ON public.iniciacao_cientifica;
CREATE POLICY "iniciacao_cientifica_delete" ON public.iniciacao_cientifica
  FOR DELETE TO authenticated
  USING (get_user_role() = ANY (ARRAY['admin'::text, 'editor'::text]));
